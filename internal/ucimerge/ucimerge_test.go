// Taking over layer 2 means dropping the local bridge definition, because
// `config device` has no `disabled` option. Two sections naming the same bridge
// is exactly what we must not ship.
func TestMergeReplacesLocalDeviceSections(t *testing.T) {
	local := `config interface 'loopback'
	option device 'lo'

config device
	option name 'br-lan'
	option type 'bridge'
	list ports 'lan2'

config interface 'lan'
	option device 'br-lan.1'
	list ipaddr '10.0.10.251/24'
`
	incoming := `config device 'ac_bridge'
	option name 'br-lan'
	option type 'bridge'
	list ports 'lan2'
	list ports 'lan3'

config interface 'ac_lan'
	option device 'br-lan.1'
	list ipaddr '10.0.10.251/24'
`
	got := Merge(local, incoming, Options{
		DisableLocal: true,
		DisableTypes: []string{"interface"},
		ReplaceTypes: []string{"device", "bridge-vlan"},
	})

	if strings.Contains(got, "config device\n") {
		t.Error("local anonymous device section survived; netifd would see two br-lan definitions")
	}
	if n := strings.Count(got, "option name 'br-lan'"); n != 1 {
		t.Errorf("br-lan defined %d times, want 1", n)
	}
	// The local interface stays, disabled, so a rollback is one line.
	if !strings.Contains(got, "config interface 'lan'") {
		t.Error("local interface was deleted instead of disabled")
	}
	if !strings.Contains(got, "config interface 'ac_lan'") {
		t.Error("managed interface missing")
	}
	if !strings.Contains(got, "config interface 'loopback'") {
		t.Error("unrelated local section was dropped")
	}
}

// The safety half: a package that does not describe devices must never delete
// the device's own network configuration. A wireless-only push reaches here with
// an empty network file.
func TestMergeKeepsLocalNetworkWhenPackageIsSilent(t *testing.T) {
	local := `config device
	option name 'br-lan'
	option type 'bridge'

config bridge-vlan
	option device 'br-lan'
	option vlan '1'
`
	// ReplaceTypes is requested but incoming carries neither type.
	got := Merge(local, `config interface 'ac_lan'
	option device 'br-lan.1'
`, Options{
		DisableLocal: true,
		DisableTypes: []string{"interface"},
		ReplaceTypes: []string{"device", "bridge-vlan"},
	})

	if !strings.Contains(got, "option name 'br-lan'") {
		t.Error("device section deleted even though the package has no device sections")
	}
	if !strings.Contains(got, "config bridge-vlan") {
		t.Error("bridge-vlan deleted even though the package has none")
	}
}

// The factory image ships `wan` and `wan6` on the raw wan port. Once the
// controller's bridge owns wan those interfaces cannot carry L3 any more, so
// they must be dropped rather than left behind in routing mode (observed on
// 10.0.10.250 after its first adoption).
func TestMergeDropsInterfacesOnManagedBridgePorts(t *testing.T) {
	local := `config interface 'loopback'
	option device 'lo'
	option proto 'static'
	list ipaddr '127.0.0.1/8'

config interface 'wan'
	option device 'wan'
	option proto 'dhcp'

config interface 'wan6'
	option device 'wan'
	option proto 'dhcpv6'

config interface 'lan'
	option device 'br-lan'
	option proto 'static'
	option ipaddr '192.168.1.1/24'

config device
	option name 'br-lan'
	option type 'bridge'
	list ports 'lan2'
	list ports 'lan3'
	list ports 'wan'
`
	incoming := `config device 'ac_bridge'
	option name 'br-lan'
	option type 'bridge'
	list ports 'lan2'
	list ports 'lan3'
	list ports 'wan'

config interface 'lan'
	option device 'br-lan.1'
	option proto 'static'
	list ipaddr '10.0.10.250/24'
`
	got := Merge(local, incoming, Options{
		ReplaceTypes:                []string{"device", "bridge-vlan"},
		ProtectNames:                []string{"loopback"},
		DropInterfacesOnBridgePorts: true,
	})

	for _, gone := range []string{"config interface 'wan'", "config interface 'wan6'"} {
		if strings.Contains(got, gone+"\n") {
			t.Errorf("%s survived although its device is a bridge port:\n%s", gone, got)
		}
	}
	if !strings.Contains(got, "config interface 'loopback'") {
		t.Error("loopback was dropped")
	}
	if !strings.Contains(got, "10.0.10.250/24") {
		t.Error("managed lan interface missing")
	}
	if strings.Contains(got, "192.168.1.1/24") {
		t.Error("local lan interface was not replaced by the managed one")
	}
}

