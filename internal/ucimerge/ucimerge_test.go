// loopback is an `interface` like any other, so the rule that disables local
// interfaces would disable it too — and take the device's stack down with it.
func TestMergeNeverDisablesLoopback(t *testing.T) {
	local := `config interface 'loopback'
	option device 'lo'
	option proto 'static'
	list ipaddr '127.0.0.1/8'

config interface 'lan'
	option device 'br-lan.1'
`
	got := Merge(local, `config interface 'ac_lan'
	option device 'br-lan.1'
`, Options{
		DisableLocal: true,
		DisableTypes: []string{"interface"},
		ProtectNames: []string{"loopback"},
	})

	if strings.Contains(got, "config interface 'loopback'\n\toption disabled") {
		t.Error("loopback was disabled")
	}
	loop := got[strings.Index(got, "config interface 'loopback'"):]
	if strings.Contains(loop[:strings.Index(loop[1:], "config ")+1], "disabled") {
		t.Errorf("loopback section carries a disabled option:/n%s", loop[:200])
	}
	if !strings.Contains(got, "config interface 'lan'\n\toption disabled '1'") {
		t.Error("local lan interface was not disabled")
	}
}

// The state 10.0.30.251 was left in, and the fix that has to pull it back out.
//
// An earlier revision rendered `config interface 'ac_lan3'` and disabled the
// device's own `lan3`. The firewall zone lists lan3 by name, so with the zone
// resolving to no device and the default INPUT policy being REJECT, the AP
// became unreachable while still heartbeating: ARP bypasses netfilter and
// OUTPUT was still ACCEPT.
//
// Merging the corrected package must retire the ac_ interfaces, restore lan3
// in place, and leave loopback and anything local alone.
func TestMergeRecoversFromPrefixedInterfaces(t *testing.T) {
	broken := `config interface 'loopback'
	option device 'lo'
	option proto 'static'
	list ipaddr '127.0.0.1/8'

config interface 'lan3'
	option device 'br-lan.3'
	option proto 'static'
	option disabled '1'
	list ipaddr '10.0.30.251'

config interface 'ac_lan3'
	option device 'br-lan.3'
	option proto 'static'
	list ipaddr '10.0.30.251'

config interface 'uplink'
	option device 'wan'
	option proto 'dhcp'
`

	incoming := `config device 'ac_bridge'
	option name 'br-lan'
	option type 'bridge'
	list ports 'lan3'
	list ports 'wan'

config bridge-vlan 'ac_bvlan3'
	option device 'br-lan'
	option vlan '3'
	list ports 'lan3:u*'
	list ports 'wan:t'

config interface 'lan3'
	option device 'br-lan.3'
	option proto 'static'
	list ipaddr '10.0.30.251'
`

	got := Merge(broken, incoming, Options{
		ReplaceTypes: []string{"device", "bridge-vlan"},
		ProtectNames: []string{"loopback"},
	})

	if strings.Contains(got, "ac_lan3") {
		t.Errorf("stale controller interface survived:/n%s", got)
	}
	// One lan3, enabled, with the address on it.
	if n := strings.Count(got, "config interface 'lan3'"); n != 1 {
		t.Errorf("got %d lan3 sections:/n%s", n, got)
	}
	if strings.Contains(got, "config interface 'lan3'\n\toption device 'br-lan.3'\n\toption proto 'static'\n\toption disabled '1'") {
		t.Error("lan3 is still disabled")
	}
	// loopback and a local interface the controller never heard of.
	if !strings.Contains(got, "config interface 'loopback'") {
		t.Errorf("loopback lost:/n%s", got)
	}
	if !strings.Contains(got, "config interface 'uplink'") {
		t.Errorf("local uplink lost:/n%s", got)
	}

	// Idempotent: merging again changes nothing.
	if again := Merge(got, incoming, Options{
		ReplaceTypes: []string{"device", "bridge-vlan"},
		ProtectNames: []string{"loopback"},
	}); again != got {
		t.Errorf("merge is not idempotent:/n%s", again)
	}
}
