// The whole point of the merge: the uplink must survive untouched.
func TestMergePreservesLocalSections(t *testing.T) {
	got := Merge(localNetwork, acNetwork, Options{})

	for _, want := range []string{
		"config interface 'loopback'",
		"config device 'br_lan'",
		"config interface 'lan'",
		"option ipaddr '10.0.10.250'",
		"option gateway '10.0.10.1'",
		"list ports 'wan'",
		"config device 'ac_br_lan_10'",
		"config interface 'ac_vlan10'",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("merged network missing %q\n%s", want, got)
		}
	}
}

func TestMergeAppendsACAfterLocal(t *testing.T) {
	got := Merge(localNetwork, acNetwork, Options{})
	lan := strings.Index(got, "config interface 'lan'")
	ac := strings.Index(got, "config interface 'ac_vlan10'")
	if lan < 0 || ac < 0 {
		t.Fatalf("sections missing\n%s", got)
	}
	if ac < lan {
		t.Errorf("ac_ sections must come after local ones\n%s", got)
	}
}

func TestMergeReplacesPreviousAC(t *testing.T) {
	first := Merge(localNetwork, acNetwork, Options{})
	// A second revision moves the VLAN from 10 to 20.
	second := Merge(first, strings.ReplaceAll(acNetwork, "10", "20"), Options{})

	if strings.Contains(second, "ac_vlan10") || strings.Contains(second, "br-lan.10") {
		t.Errorf("stale ac_ section survived\n%s", second)
	}
	if !strings.Contains(second, "config interface 'ac_vlan20'") {
		t.Errorf("new ac_ section missing\n%s", second)
	}
	if strings.Count(second, "config interface 'ac_vlan20'") != 1 {
		t.Errorf("ac_ section duplicated\n%s", second)
	}
}

func TestMergeIsIdempotent(t *testing.T) {
	once := Merge(localNetwork, acNetwork, Options{})
	twice := Merge(once, acNetwork, Options{})
	if once != twice {
		t.Errorf("merge is not idempotent\n--- once ---\n%s\n--- twice ---\n%s", once, twice)
	}
}

func TestDisableLocalWirelessSections(t *testing.T) {
	got := Merge(localWireless, acWireless, Options{
		DisableLocal: true,
		DisableTypes: []string{"wifi-device", "wifi-iface"},
	})

	if !strings.Contains(got, "config wifi-iface 'default_radio0'") {
		t.Fatalf("local section deleted, it must only be disabled\n%s", got)
	}
	// The local device had disabled '0' and must be flipped.
	if !strings.Contains(got, "option disabled '1'") {
		t.Errorf("local sections not disabled\n%s", got)
	}
	// The ac_ radio keeps disabled '0'.
	if strings.Count(got, "option disabled '1'") != 2 {
		t.Errorf("expected exactly 2 disabled sections (local device + local iface)\n%s", got)
	}
	if !strings.Contains(got, "config wifi-iface 'ac_ssid_corp_2g'") {
		t.Errorf("managed section missing\n%s", got)
	}
}

func TestDisableDoesNotDuplicateOption(t *testing.T) {
	got := Merge(localWireless, acWireless, Options{
		DisableLocal: true,
		DisableTypes: []string{"wifi-device", "wifi-iface"},
	})
	section := got[strings.Index(got, "config wifi-device 'radio0'"):]
	section = section[:strings.Index(section, "config wifi-iface")]
	if n := strings.Count(section, "option disabled"); n != 1 {
		t.Errorf("disabled option appears %d times in local radio\n%s", n, section)
	}
}

func TestPreambleCommentSurvives(t *testing.T) {
	existing := "# generated by hand, keep me\n\n" + localNetwork
	got := Merge(existing, acNetwork, Options{})
	if !strings.HasPrefix(got, "# generated by hand, keep me\n\nconfig interface 'loopback'") {
		t.Errorf("preamble lost or reformatted\n%s", got)
	}
}

func TestMergeIntoEmptyFile(t *testing.T) {
	got := Merge("", acNetwork, Options{})
	if !strings.Contains(got, "config interface 'ac_vlan10'") {
		t.Errorf("merge into empty file failed\n%s", got)
	}
	if strings.HasPrefix(got, "\n") {
		t.Errorf("output starts with a blank line\n%q", got)
	}
}

func TestACNames(t *testing.T) {
	names := ACNames(acNetwork)
	want := []string{"ac_br_lan_10", "ac_vlan10"}
	if len(names) != len(want) {
		t.Fatalf("names = %v, want %v", names, want)
	}
	for i := range want {
		if names[i] != want[i] {
			t.Errorf("names[%d] = %q, want %q", i, names[i], want[i])
		}
	}
	if got := ACNames(localNetwork); len(got) != 0 {
		t.Errorf("local file reported ac_ names: %v", got)
	}
}

func TestValidate(t *testing.T) {
	if err := Validate(acNetwork); err != nil {
		t.Errorf("valid output rejected: %v", err)
	}
	if err := Validate(localNetwork); err == nil {
		t.Error("file with no ac_ sections accepted")
	}

	dup := acNetwork + "\nconfig interface 'ac_vlan10'\n\toption proto 'none'\n"
	if err := Validate(dup); err == nil {
		t.Error("duplicate section accepted")
	}
}

